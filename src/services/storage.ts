export function getStoredTags(): Tag[] {
  // One-time forced reset of categories as requested by the user
  try {
    if (typeof window !== 'undefined' && window.localStorage && !localStorage.getItem('theparlor_cashflow_categories_reset_v4')) {
      localStorage.setItem(STORAGE_KEYS.TAGS, JSON.stringify(INITIAL_TAGS));
      localStorage.setItem('theparlor_cashflow_categories_reset_v4', 'true');
      return INITIAL_TAGS;
    }
  } catch (e) {
    console.error('Error running one-time categories reset', e);
  }

  try {
    const item = localStorage.getItem(STORAGE_KEYS.TAGS);
    if (item) {
      const parsed = JSON.parse(item);
      if (Array.isArray(parsed) && parsed.length > 0) {
        // Guarantee every category tag has a valid name, color, and optional observation
        return parsed.map((tag: Tag, idx: number) => {
          const categoryName = tag.name || tag.code || `Categoria ${idx + 1}`;
          const matchingInitial = INITIAL_TAGS.find(
            (it) => it.name.toLowerCase() === categoryName.toLowerCase() || (it.code && tag.code && it.code.toUpperCase() === tag.code.toUpperCase())
          );
          return {
            ...tag,
            name: categoryName,
            color: tag.color || matchingInitial?.color || DEFAULT_PALETTE[idx % DEFAULT_PALETTE.length],
            observation: tag.observation || matchingInitial?.observation || '',
          };
        });
      }
    }
  } catch (e) {
    console.error('Error loading tags/categories from storage', e);
  }
  // Fallback & seed
  localStorage.setItem(STORAGE_KEYS.TAGS, JSON.stringify(INITIAL_TAGS));
  return INITIAL_TAGS;
}

